//  P38 — ★ ЗАЩИТА ЛИМИТА МЕСТ КЛАНА: проверка расширения сверяет ТУ ЖЕ прибавку (+10)
//  [ОРИГИНАЛ] дефект оригинала (решение владельца 27.09.2026, закон fix-original-defects).
//  Разбор: ревизия Reports/owner_0927/who_clan_REVIEW.md §4;
//  документ — AstoryServer/Docs/GameServer/clan-slot-cap-p38.md
//
//  ── ДЕФЕКТ ──
//  Обработчик расширения клана (UPClanCreate/… @0x40494B) проверяет «текущий_лимит + 5 <= 100»,
//  а ПРИБАВЛЯЕТ +10 (0x404ADA/0x404AE8). Формула стартового лимита — 50, шаги по +10 (5 ступеней):
//  50 → 60 → 70 → 80 → 90 → 100. В обычной игре 100 не превышается. Но при РУЧНОЙ правке БД
//  (или у старых кланов), если лимит оканчивается на 1…5 и > 90, проверка «лимит+5 <= 100»
//  проходит, а прибавляется +10 — клан уходит ЗА 100 (до 105).
//
//  ── ЧЕМ ЛЕЧИМ ──
//  Один байт: проверка должна сверять ту же прибавку, что и делает. `add ecx,5` (0x40494B
//  `83 C1 05`) → `add ecx,10` (`83 C1 0A`): меняется только immediate по адресу 0x40494D
//  (05 → 0A). Тогда гейт = «текущий_лимит + 10 <= 100», и результат прибавки (+10) никогда не
//  превысит 100. Честный путь (лимит ≤ 90) не задет: 90+10=100 ≤ 100 — расширение проходит.
//  Протокол НЕ меняется, отказ — штатный (код 3 → нотис 12453 «клану больше некуда расти»).
//
//  ── ПЛОЩАДКА (1 байт; площадки основного GameServer и Indun) ──
//    0x00404944  0F B6 8D 65 FF FF FF   movzx ecx,[ebp-0x9B]   (текущий лимит)
//    0x0040494B  83 C1 05               add   ecx,5            ← imm по 0x40494D
//    0x0040494E  83 F9 64               cmp   ecx,100
//    0x00404951  7E 34                  jle   (расширение разрешено)
//  Байты 0x404944…0x404951 одинаковы в живом GameServer, живом Indun_GameServer и базе IDA
//  (md5 e7b4ac38). С P01…P42 не пересекается (grep адресов, verify_dll.py).
//
//  ── ЗАМЕЧАНИЕ (МЕЛК-5 ревизии, НЕ лечится здесь) ──
//  Соседний гейт `cmp eax,5; jne` ловит только «== 5»; при v25 > 5 из БД цена читается за
//  границей 5-элементного массива. Достижимо ТОЛЬКО ручной правкой БД, к переполнению лимита
//  отношения не имеет — оставлено как есть (правка данных, не кода).
// ─────────────────────────────────────────────────────────────────────────────
#include "Patches.h"
#include "../Hook.h"
#include "../Log.h"
#include "../Config.h"

namespace
{
    const wchar_t* const S = L"P38_ClanSlotCap";

    constexpr DWORD kAddImmVA = 0x0040494D;   // immediate инструкции `add ecx,5`
    constexpr BYTE  kOrig     = 0x05;         // сток: +5 (не совпадает с реальной прибавкой +10)
    constexpr BYTE  kPatched  = 0x0A;         // лечим: +10 (как реальная прибавка)

    // Окружение сверяем целиком — чтобы не попасть в чужую `add ecx,5`.
    constexpr DWORD kCtxVA = 0x00404944;
    const BYTE kCtx[] = { 0x0F, 0xB6, 0x8D, 0x65, 0xFF, 0xFF, 0xFF,   // movzx ecx,[ebp-0x9B]
                          0x83, 0xC1, 0x05, 0x83, 0xF9, 0x64, 0x7E }; // add ecx,5; cmp ecx,100; jle
}

PatchResult P38_ClanSlotCap()
{
    if (!Config::GetBool(S, L"Enabled", true)) { return PatchResult::Disabled; }

    // Сверка окружения до записи.
    Site sites[1] = { { kCtxVA, kCtx, sizeof(kCtx) } };
    if (!VerifyAllSites(L"P38", sites, 1)) { return PatchResult::Mismatch; }

    if (!Hook::WriteByteChecked(kAddImmVA, kOrig, kPatched)) { return PatchResult::Failed; }

    Log::Line(L"    P38: лимит мест клана — проверка сверяет ту же прибавку (+10 <= 100), "
              L"за 100 клан больше не уходит (0x%08X: 05 -> 0A)", (unsigned)kAddImmVA);
    return PatchResult::Applied;
}
