    // ═══════════════════════════ построитель текста ═══════════════════════════
    // Растущий буфер UTF-16 (только фоновый поток).
    struct WBuf
    {
        wchar_t* p = nullptr; int n = 0; int cap = 0;
        ~WBuf() { if (p) { HeapFree(GetProcessHeap(), 0, p); } }
        bool Reserve(int add)
        {
            if (n + add + 1 <= cap) { return true; }
            int nc = cap ? cap : 65536;
            while (nc < n + add + 1) { nc *= 2; }
            wchar_t* q = (wchar_t*)(p ? HeapReAlloc(GetProcessHeap(), 0, p, nc * sizeof(wchar_t))
                                      : HeapAlloc(GetProcessHeap(), 0, nc * sizeof(wchar_t)));
            if (!q) { return false; }
            p = q; cap = nc; return true;
        }
        void S(const wchar_t* s) { const int l = lstrlenW(s); if (Reserve(l)) { memcpy(p + n, s, l * sizeof(wchar_t)); n += l; p[n] = 0; } }
        void C(wchar_t c) { if (Reserve(1)) { p[n++] = c; p[n] = 0; } }
        void Int(int v)            { if (v == AcJournal::kNone) { S(L"NULL"); return; } wchar_t t[16]; wsprintfW(t, L"%d", v); S(t); }
        void I64(__int64 v, bool has) { if (!has) { S(L"NULL"); return; } wchar_t t[32]; _snwprintf_s(t, _TRUNCATE, L"%I64d", v); S(t); }
        void Bit(int v)            { if (v == AcJournal::kNone) { S(L"NULL"); return; } S(v ? L"1" : L"0"); }
        // N'…' с удвоением апострофов; nullptr/пусто → NULL.
        // [fix2, 2026-10-13] maxChars — ширина колонки NVARCHAR(n) в символах UTF-16 (константы kCol* выше): значение
        //   длиннее обрезается ДО экранирования, пара суррогатов не разрывается. Страховка СРЕДН-3 ревизии INTEG3: строка
        //   шире колонки при ANSI_WARNINGS (ODBC) + XACT_ABORT откатывала ВЕСЬ пакет с чужими годными событиями.
        void Str(const wchar_t* s, int maxChars)
        {
            if (!s || !*s) { S(L"NULL"); return; }
            int len = 0;
            while (s[len] && len < maxChars) { ++len; }
            if (len == maxChars && s[len] && len > 0 && s[len - 1] >= 0xD800 && s[len - 1] <= 0xDBFF) { --len; }   // не рвать суррогат
            S(L"N'");
            for (int i = 0; i < len; ++i) { const wchar_t ch = s[i]; if (ch == L'\'') { C(L'\''); } C(ch < 0x20 ? L' ' : ch); }
            C(L'\'');
        }
        // '…' для ASCII-строк (IP, адрес)
        void Ascii(const char* s)
        {
            if (!s || !*s) { S(L"NULL"); return; }
            C(L'\'');
            for (const char* q = s; *q; ++q) { const wchar_t c = (wchar_t)(BYTE)*q; if (c == L'\'') { C(L'\''); } C(c < 0x20 || c > 0x7E ? L'?' : c); }
            C(L'\'');
        }
        void Clear() { n = 0; if (p) { p[0] = 0; } }
    };

    // FILETIME → '2026-10-12T13:45:01.123' (UTC и местное).
    void AppendTimes(WBuf& b, __int64 ft)
    {
        FILETIME f; f.dwLowDateTime = (DWORD)ft; f.dwHighDateTime = (DWORD)(ft >> 32);
        SYSTEMTIME u = {}, l = {};
        FileTimeToSystemTime(&f, &u);
        if (!SystemTimeToTzSpecificLocalTime(nullptr, &u, &l)) { l = u; }
        wchar_t t[64];
        wsprintfW(t, L"'%04d-%02d-%02dT%02d:%02d:%02d.%03d', '%04d-%02d-%02dT%02d:%02d:%02d.%03d'",
                  u.wYear, u.wMonth, u.wDay, u.wHour, u.wMinute, u.wSecond, u.wMilliseconds,
                  l.wYear, l.wMonth, l.wDay, l.wHour, l.wMinute, l.wSecond, l.wMilliseconds);
        b.S(t);
    }

    // Имя персонажа cp1251 → UTF-16 (без управляющих символов).
    void NameW(const char* s, wchar_t* out, int cch)
    {
        out[0] = 0;
        int len = 0;
        while (len < 23 && s[len]) { ++len; }
        if (!len) { return; }
        const int n = MultiByteToWideChar(g_nameCp, 0, s, len, out, cch - 1);
        out[n > 0 ? n : 0] = 0;
    }

    void TextW(const char* s, wchar_t* out, int cch)
    {
        out[0] = 0;
        int len = 0;
        while (len < 63 && s[len]) { ++len; }
        if (!len) { return; }
        const int n = MultiByteToWideChar(g_nameCp, 0, s, len, out, cch - 1);
        out[n > 0 ? n : 0] = 0;
    }

