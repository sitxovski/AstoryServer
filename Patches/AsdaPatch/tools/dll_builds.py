def place(product, h):
    """Номер сборки в цепочке продукта (None — незнакомый md5) и её подпись."""
    for i, (m, label) in enumerate(CHAINS.get(product, [])):
        if m == h:
            return i, label
    return None, ""


def accept(product, got, want, log_ok, where, log=print):
    """Сверка md5 DLL на стойке с ожидаемой сборкой скрипта. log_ok — журнал патчей этой папки подтвердил патч (patchlog).
    Возврат: принять ли (своя сборка; или более поздняя сборка цепочки при log_ok). Строка — в log."""
    if got == want:
        log("%s: %s %s — своя сборка" % (where, got, place(product, got)[1] or "ожидаемая"))
        return True
    gi, glabel = place(product, got)
    wi, _ = place(product, want)
    if gi is not None and wi is not None and gi > wi:
        if log_ok:
            log("%s: %s — сведения: сборка новее (%s), журнал подтвердил патч" % (where, got, glabel))
            return True
        log("%s: %s — сборка новее (%s), но журнал патч НЕ подтвердил — ПРОВАЛ" % (where, got, glabel))
        return False
    if gi is not None and wi is not None:
        log("%s: %s — сборка СТАРЕЕ ожидаемой (%s) — ПРОВАЛ" % (where, got, glabel))
        return False
    log("%s: %s — незнакомый md5 (нет в реестре dll_builds.%s), ожидался %s — ПРОВАЛ" % (where, got, product, want))
    return False
