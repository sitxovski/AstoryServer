def sections(data):
    pe = struct.unpack_from('<I', data, 0x3C)[0]
    n = struct.unpack_from('<H', data, pe + 6)[0]
    opt = pe + 24
    base = struct.unpack_from('<I', data, opt + 28)[0]
    sh = opt + struct.unpack_from('<H', data, pe + 20)[0]
    secs = []
    for i in range(n):
        o = sh + 40 * i
        vsz, va, rsz, ra = struct.unpack_from('<IIII', data, o + 8)
        secs.append((va, vsz, ra, rsz))
    return base, secs


def va2off(base, secs, va):
    rva = va - base
    for v, vsz, ra, rsz in secs:
        if v <= rva < v + max(vsz, rsz):
            return ra + (rva - v)
    return None


