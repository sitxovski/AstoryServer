// ⚠ Смещения в __asm — ТОЛЬКО #define (см. n03/n04: MSVC подставлял адрес константы вместо значения).
#define MOB_WAIT_TICK 7A68h     // +31336: метка начала ожидания ATTACK_WAIT (у монстра всегда 0)

