PatchResult N18_TickSigned()
{
    if (!Config::GetBool(S, L"Enabled", true))
        return PatchResult::Disabled;
    const bool on[4] = { false,
                         Config::GetBool(S, L"FixSoulmateSkill", true),
                         Config::GetBool(S, L"FixItemEvent", true),
                         Config::GetBool(S, L"FixAttackWait", true) };
    if (!on[1] && !on[2] && !on[3])
        return PatchResult::Disabled;

    // Правило проекта: ни один патч не пишет байты, не сверив ВСЕ свои площадки.
    Site sites[ARRAYSIZE(kAreas)];
    int n = 0;
    for (const Area& a : kAreas)
        if (on[a.group])
            sites[n++] = { a.va, a.orig, (SIZE_T)a.len };
    if (!VerifyAllSites(S, sites, n))
        return PatchResult::Mismatch;

    for (const Area& a : kAreas)
    {
        if (!on[a.group]) continue;
        if (a.group == 3)
        {
            static const BYTE kNop2[] = { 0x90, 0x90 };
            static const BYTE kJb[]   = { 0x82 };
            if (!Hook::WriteCall(kAwSub, (void*)&St18_AttackWait, 6)) return PatchResult::Failed;   // call + nop
            if (!Hook::WriteBytes(kAwCmp, kNop2, sizeof(kNop2)))      return PatchResult::Failed;   // cmp eax,ecx → nop×2
            if (!Hook::WriteBytes(kAwJl + 1, kJb, sizeof(kJb)))       return PatchResult::Failed;   // jl → jb
            continue;
        }
        for (int i = 0; i < a.ne; ++i)
            if (!Hook::WriteByteChecked(a.e[i].va, a.e[i].from, a.e[i].to)) return PatchResult::Failed;
    }
    for (const Area& a : kAreas)
        if (on[a.group])
            Log::Line(L"    0x%06X %ls", a.va, a.where);
    Log::Line(L"    знаковые сравнения такта — модульные/беззнаковые (группы: соулмейт %d, событие %d, ATTACK_WAIT %d): "
              L"при аптайме хоста > 24,8 сут и при переходе через 2^32 логика как при малом аптайме", on[1], on[2], on[3]);
    return PatchResult::Applied;
}
