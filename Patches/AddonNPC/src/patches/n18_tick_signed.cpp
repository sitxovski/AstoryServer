// число он отрицателен, и всё, что сток сравнивает знаково с тактом, «ломается». Три логики (кроме N17):
//
//  Г1. НАВЫКИ СОУЛМЕЙТА ПО ИГРОКУ / ПО МОНСТРУ (ProcessSoulmateSkillDamageToUserStart sub_415DE0, …ToMonsterStart
//      sub_416790). Навык с флагом записи +0x3A (SoulmateSkill.ssi) идёт в две фазы: первый вызов — «начало» (201/8228
//      подкод 20, метка игрока +0x10A88 := такт), второй в течение 2 с — урон (метка := 0). Проверка
//      `(такт − метка) < 2000` ЗНАКОВАЯ (`jl` @0x415EE7, @0x416899): при такте ≥ 2^31 и метке 0 разность отрицательна —
//      «начало» пропускается, урон сразу на каждом вызове. Метка — 0 (инициализация игрока 0x428DB6, после урона
//      0x415F50/0x4168F4) или свой свежий такт той же функции (0x415EF2/0x41689B: GetTickCount двумя инструкциями выше);
//      будущих меток нет. Правка: `jl` → `jb` (7C → 72). Беззнаковая разность верна при любом переходе.
//      ⚠ На dev (сток/живой/Indun — SoulmateSkill.ssi a8db1d51, 45 записей) флаг +0x3A = 0 у ВСЕХ навыков: ветка
//      сейчас недостижима. Правка — на случай, если таблица изменится (поведение при флаге 0 не меняется).
//
//  Г2. СОБЫТИЕ «1000 ПРЕДМЕТОВ → 1 ЧАС» (sub_41DDD0 сдача предмета; кадр сервера sub_44DB70 — площадки 0x44E0BA…0x44E2A8).
//      dword_47D2BC = такт + 300000 — НАЧАЛО события (через 5 мин после тысячного предмета), 0 — события нет.
//      Сток: «событие есть» ⇔ метка > 0 (ЗНАКОВО), «уже началось» ⇔ метка ≤ такт (беззнаково), «кончилось» ⇔
//      (такт − метка) ≥ 3600000 (ЗНАКОВО). При такте ≥ 2^31 метка «отрицательна» → события «нет»: нет «Event End»/8921 и
//      оповещений 8919, предметы копятся как без события, событие можно перезапускать. Множитель добычи (sub_437A30,
//      `такт − метка − 1 > 0x36EE7E` беззнаково) свой час отрабатывает — его не трогаем.
//      Правка: «> 0 / ≤ 0» → «≠ 0 / = 0» (`0F 8E`→`0F 84` @0x41DE4E, 0x44E0BC, 0x44E1EE; `7E`→`74` @0x41DF1E;
//      `7F`→`75` @0x44E2A8); «кончилось» `jge` → `jae` (@0x41DE6A, 0x44E0D3, 0x44E205).
//      ★ Сверх аудита (иначе переход через 2^32 «вешает» событие): «уже началось» сток проверяет `cmp метка, такт; ja`
//      — абсолютно. Событие, начавшееся до перехода такта через 2^32 (метка ~0xFFxxxxxx, такт после перехода мал),
//      считалось бы «ещё не начавшимся» 49,7 сут (не кончается, сдача уходит в резерв, перезапуск невозможен);
//      а метка, перевалившая 2^32 при взводе (такт + 300000), — «уже идущим». Замена: `cmp такт, метка; js` (операнды
//      местами + `0F 87`→`0F 88`): «ещё не началось» ⇔ (int)(такт − метка) < 0 — модульная разность. Метка и такт
//      читаются под одной критической секцией (`CriticalSection` @0x47CF8C, обе функции), метка ≤ такт + 300000,
//      устаревших меток нет (каждые 60/300 кадров событие закрывается по сроку). Флаги после — не читаются (дальше
//      `sub такт, метка` / fld-fcomp). При js-проверке на ветке «идёт» разность ∈ [0, 2^31) — `jae` ≡ `jge`.
//      Метка 0 как «нет события»: если такт + 300000 даст ровно 0 (1 мс из 49,7 сут) — событие не стартует (как и в
//      стоке при метке 0); пренебрежимо.
//
//  Г3. ДЕЙСТВИЕ 6 ATTACK_WAIT (sub_4390A0, зовётся ProcessAction @0x44BC5B; ebx = такт кадра, esi = монстр):
//      `(такт − [M+7A68h]) < (i16)[M+7A6Ch]` ЗНАКОВО (`jl` @0x4390B9) → ждать. У монстра +7A68 — не такт: пишут
//      только конструктор (0x44BF73/0x44C115, нулём) и AlarmMonsterAction (0x460CB7, нулём); 0x42E4BF — область без
//      ссылок (как у N17). При такте ≥ 2^31: такт − 0 < 0 → монстр в ATTACK_WAIT навсегда (до внешней смены действия).
//      Правка — стаб как в N17: ждать ⇔ длительность > 0 И (беззн.)(такт − метка) < длительность. Площадка НЕ сплошная:
//      `sub eax,[esi+7A68h]` (0x4390B0, 6 б) → `call стаб` + nop; `push edi` (0x4390B6) — остаётся; `cmp eax,ecx`
//      (0x4390B7) → nop nop; `jl` → `jb`. push флаги не меняет. eax после стаба = такт − метка (как в стоке; функция
//      возвращает ax). Голый `jb` нельзя: при длительности < 0 он «ждал» бы, а сток не ждёт.
//
// ⚠ ПРЕДОСТЕРЕЖЕНИЕ АУДИТА (§4) СОБЛЮДЕНО: поля, которые пишутся свежим тактом ПОСЛЕ такта кадра (состояния монстра
//   `sub_4103F0` → 88 площадок `sub_443740`, задержка смерти +8F72, +8644), НЕ ТРОНУТЫ — сток опирается на знак, чтобы
//   терпеть разность −16 мс. У всех трёх групп N18 такой записи нет (разобрано выше).
// Образы: сток 16c7a0af, живой NpcServer c02486d6, Indun 0de2c559 — площадки побайтно одинаковы (verify_n18.py).
// Правило: сначала сверяются ВСЕ площадки включённых групп, и только потом что-то пишется.
