//
// СИМПТОМ
//   Полоса здоровья монстра уже пустая, а монстр жив и продолжает драться.
//   Владелец 24.08.2026: «бывают случаи, когда у нас уже пустая полоса, а моб ещё живёт».
//
// МЕХАНИЗМ (сверено по коду сервера, а не по клиенту)
//   Первые ~2 секунды боя монстр «спит»: его здоровье `+30853` не меняется, а весь урон копится
//   в накопителе `+34376`. Копит `CMonster::DamageAndHateCheck` (`NpcServer.exe.c:47219-47235`):
//
//       v22 = mob[30853];              // текущее здоровье
//       v23 = a5;                      // урон
//       if ( v22 - a5 <= 0 )           // урон покрывает всё здоровье
//       {
//           v23 = v22 + a5;            // ★ ЗДОРОВЬЕ ПЛЮС УРОН
//           a5 += v22;                 // ★ и то же самое в сам урон
//       }
//       mob[34376] += v23;             // копим
//
//   Замысел ветки очевиден: «этот удар добивает — записать ровно остаток здоровья». Написано же
//   СЛОЖЕНИЕ вместо присваивания, и в накопитель уходит `здоровье + урон`.
//
//   Клиенту здоровье монстра уходит как `здоровье − накопитель` с зажимом в ноль (пакеты 8202 и
//   8204). Раз накопитель заведомо больше здоровья, разность уходит в минус, зажимается в ноль —
//   и клиент честно рисует пустую полосу у монстра, который ещё жив. Умрёт он только когда
//   накопитель сольётся (`ProcessState`, через 2000 мс), и вот тогда сравнение
//   `здоровье − накопитель < 0` действительно отправит его в смерть.
//
//   В дизассемблере (`0x4427D6`):
//       mov  eax, [esi+7885h]     ; здоровье
//       mov  ecx, [ebp+14h]       ; урон
//       mov  edx, eax
//       sub  edx, ecx             ; здоровье − урон
//       test edx, edx
//       jg   +5                   ; > 0 — обычный случай, мимо
//       add  ecx, eax             ; ★ ДЕФЕКТ: урон += здоровье
//       mov  [ebp+14h], ecx
//       add  [esi+8648h], ecx     ; накопитель += ecx
//
// ЧТО ДЕЛАЕМ
//   `add ecx, eax` → `mov ecx, eax`. Два байта, длина та же. В накопитель уходит ровно остаток
//   здоровья, разность `здоровье − накопитель` больше не уходит в минус, и полоса пустеет ровно
//   тогда, когда монстр действительно доведён до нуля.
//   Значение урона `[ebp+14h]` получает то же исправленное число — оно и есть фактически
//   нанесённый урон: больше, чем осталось здоровья, нанести нельзя.
//
// ⚠ Байты выверены на образе NpcServer.exe md5 d292e4ec4edfd5040d8fb39382664eab.
#include "Patches.h"
#include "../Config.h"
#include "../NpcApi.h"
#include "Hook.h"
#include "Log.h"

namespace
{
    const DWORD kVa = Npc::Hooks::kAccumOverkill;                // 0x4427E7
    const BYTE  kOrig[] = { 0x03, 0xC8 };                        // add ecx, eax
    const BYTE  kNew[]  = { 0x8B, 0xC8 };                        // mov ecx, eax
    static_assert(sizeof(kOrig) == sizeof(kNew), "длина обязана совпадать");

    const Site kSites[] = { { kVa, kOrig, sizeof(kOrig) } };
}

PatchResult N07_AccumOverkill()
{
    if (!Config::GetBool(L"N07_AccumOverkill", L"Enabled", true))
        return PatchResult::Disabled;

    if (!VerifyAllSites(L"N07_AccumOverkill", kSites, ARRAYSIZE(kSites)))
        return PatchResult::Mismatch;

    if (!Hook::WriteBytes(kVa, kNew, sizeof(kNew)))
        return PatchResult::Failed;

    Log::Line(L"    добивающий удар копится как остаток здоровья, а не «здоровье + урон» — "
              L"полоса больше не пустеет у живого монстра");
    return PatchResult::Applied;
}
