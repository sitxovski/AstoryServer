"""gen_secure_key.py - new long-term key pair of the traffic encryption (AsdaSecure: P61 GameServer, L07 LoginManager, EAC channel 15901).

    python gen_secure_key.py <secure_server.key> <server_public.h> [symbol]

Writes the same two files as Patches\\AsdaSecure\\keygen.exe (no Visual Studio needed, only "pip install cryptography"):
  * secure_server.key - PRIVATE key, 104 bytes: "ASDAKEY1" + d (32) + X||Y (64), big-endian (= BCRYPT_ECCPRIVATE_BLOB body).
    It goes next to GameServer.exe, Ch2_GameServer.exe, Indun_GameServer.exe and LoginManager.exe; EacServer reads
    ..\\GameServer\\secure_server.key. Never commit it, never send it to anybody.
  * server_public.h  - the PUBLIC key for the game client (AstoryClient\\Source\\AsdaNet\\Private\\Secure\\server_public.h).
    The client checks the ServerHello signature with it: rebuild the client after replacing the file.
A new pair = every old client stops connecting (the signature no longer matches) until it is rebuilt with the new header.
"""
import os
import sys

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec

TAG = b"ASDAKEY1"                      # kKeyFileTag (Patches/AsdaSecure/src/AsdaSecure.cpp)


def header(xy, symbol):
    """Text of server_public.h exactly like AsdaSecure::WritePublicHeader (plus the copyright line of the client sources)."""
    out = ["// Copyright (c) 2026 @sitxovski (Discord)\n",
           "// server_public.h - long-term PUBLIC key of the server (ECDSA P-256, X||Y).\n",
           "// Generated by AstoryServer\\Prerequisites\\gen_secure_key.py (same format as AsdaSecure keygen). Checks the ServerHello signature.\n",
           "// The private key lives only in secure_server.key next to the server DLLs, never in the sources.\n",
           "#pragma once\n#include <cstdint>\nstatic const uint8_t %s[64] = {\n    " % symbol]
    for i, b in enumerate(xy):
        out.append("0x%02X%s" % (b, "" if i == 63 else (",\n    " if i % 12 == 11 else ", ")))
    out.append("\n};\n")
    return "".join(out)


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    key_path, hdr_path = sys.argv[1], sys.argv[2]
    symbol = sys.argv[3] if len(sys.argv) > 3 else "kAsdaServerPublicKey"
    priv = ec.generate_private_key(ec.SECP256R1())
    nums = priv.private_numbers()
    d = nums.private_value.to_bytes(32, "big")
    xy = nums.public_numbers.x.to_bytes(32, "big") + nums.public_numbers.y.to_bytes(32, "big")
    # self-check: sign with the private key, verify with the public point read back from X||Y
    msg = os.urandom(32)
    sig = priv.sign(msg, ec.ECDSA(hashes.SHA256()))
    pub = ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256R1(), b"\x04" + xy)
    pub.verify(sig, msg, ec.ECDSA(hashes.SHA256()))
    for p in (key_path, hdr_path):
        if os.path.dirname(os.path.abspath(p)):
            os.makedirs(os.path.dirname(os.path.abspath(p)), exist_ok=True)
    with open(key_path, "wb") as f:
        f.write(TAG + d + xy)
    with open(hdr_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(header(xy, symbol))
    print("private key: %s (104 bytes) - next to the server exe files, keep it secret" % key_path)
    print("public key : %s (symbol %s) - copy into AstoryClient\\Source\\AsdaNet\\Private\\Secure\\ and rebuild the client" % (hdr_path, symbol))
    print("self-check of the signature: OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
